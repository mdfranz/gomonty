// ClassType identifies a non-builtin class crossing the sandbox boundary —
// the class half of a ClassInstance.
//
// ID is a uuid4 string identity: generated by whichever side defines the
// class (see NewClassID for the host side), never derived from a memory
// address. Set HostDefined true for a ClassInstance the host constructs to
// pass in as an input — a sandbox-defined class type (HostDefined false,
// the zero value, as read back from a Value returned by Run/FeedRun) is
// output-only and rejected if sent back in as an input.
type ClassType struct {
	Name        string `json:"name"`
	ID          string `json:"id"`
	HostDefined bool   `json:"host_defined"`
	IsDataclass bool   `json:"is_dataclass"`
	Attrs       Dict   `json:"attrs"`
}

// ClassInstance is the explicit host-side class-instance value shape. It
// replaces the pre-upstream-refresh Dataclass shape: Monty now carries
// instance identity (InstanceID, a uuid4 string) and the owning class
// (ClassType) explicitly rather than an opaque type_id.
//
// Methods are host-only metadata and are intentionally omitted from the wire
// format so Rust never stores Go function pointers or opaque Go values.
type ClassInstance struct {
	ClassType  ClassType                `json:"class_type"`
	InstanceID string                   `json:"instance_id"`
	Attrs      Dict                     `json:"attrs"`
	Methods    map[string]MethodHandler `json:"-"`
}

// Time represents a Python datetime.time value: a wall clock with no date
// attached.
type Time struct {
	Hour          uint8   `json:"hour"`
	Minute        uint8   `json:"minute"`
	Second        uint8   `json:"second"`
	Microsecond   uint32  `json:"microsecond"`
	OffsetSeconds *int32  `json:"offset_seconds,omitempty"`
	TimezoneName  *string `json:"timezone_name,omitempty"`
	Fold          uint8   `json:"fold"`
}

// FileHandle describes an open Python file object (the result of open()).
// Output-only: it carries the sandbox's virtual path and cannot be
// reconstructed as an input.
type FileHandle struct {
	Path     string `json:"path"`
	Mode     string `json:"mode"`
	Position uint64 `json:"position"`
}

// Module is a host-provided module. Returned from an import handler it
// imports as a sandbox `module` object whose attributes are Attrs; Monty
// also hands it back with the same ID when the sandbox returns one.
//
// ID is a uuid4 string identity generated by the host (see NewClassID);
// ModuleValue fills it in when empty. Attr keys are attribute names.
type Module struct {
	Name  string `json:"name"`
	ID    string `json:"id"`
	Attrs Dict   `json:"attrs"`
	// Stub is optional type-stub source for the module. It is host-only
	// metadata, never sent over the wire, and is served to the type checker
	// when RunOptions.Modules is used.
	Stub string `json:"-"`
}

// NewClassID generates a random uuid4 string identity for a host-defined
// ClassType or ClassInstance. Monty never generates ids on the host's
// behalf — hosts that build a ClassInstance are expected to call this (or
// leave the id fields empty, which ClassInstanceValue fills in the same way).
func NewClassID() string {
	var raw [16]byte
	// crypto/rand.Read on the fixed-size buffer below only errors if the OS
	// entropy source itself is unavailable, which is unrecoverable here.
	if _, err := rand.Read(raw[:]); err != nil {
		panic(fmt.Errorf("monty: failed to generate class id: %w", err))
	}
	raw[6] = (raw[6] & 0x0f) | 0x40 // version 4
	raw[8] = (raw[8] & 0x3f) | 0x80 // RFC 4122 variant
	return fmt.Sprintf("%x-%x-%x-%x-%x", raw[0:4], raw[4:6], raw[6:8], raw[8:10], raw[10:16])
}

