// OSFunction names a host OS callback that Monty requested.
type OSFunction string

const (
	OSPathExists     OSFunction = "Path.exists"
	OSPathIsFile     OSFunction = "Path.is_file"
	OSPathIsDir      OSFunction = "Path.is_dir"
	OSPathIsSymlink  OSFunction = "Path.is_symlink"
	OSPathReadText   OSFunction = "Path.read_text"
	OSPathReadBytes  OSFunction = "Path.read_bytes"
	OSPathWriteText  OSFunction = "Path.write_text"
	OSPathWriteBytes OSFunction = "Path.write_bytes"
	OSPathMkdir      OSFunction = "Path.mkdir"
	OSPathUnlink     OSFunction = "Path.unlink"
	OSPathRmdir      OSFunction = "Path.rmdir"
	OSPathIterdir    OSFunction = "Path.iterdir"
	OSPathStat       OSFunction = "Path.stat"
	OSPathRename     OSFunction = "Path.rename"
	OSPathResolve    OSFunction = "Path.resolve"
	OSPathAbsolute   OSFunction = "Path.absolute"
	// OSPathCreateExclusive creates a new empty file, refusing every existing
	// entry (open mode 'x'). Args are the path and the mode, with a
	// permissions keyword argument. It must be answered with an open-file
	// value, which gomonty cannot yet send back as a host result, so the
	// vfs handlers answer it with NotImplementedError for now.
	OSPathCreateExclusive OSFunction = "Path.create_exclusive"
	// OSGetTypeHints asks for typing.get_type_hints of a host function
	// (args "function", name) or host class (args "class", id). Reply with a
	// dict of hints; with no handler the sandbox receives an empty dict.
	OSGetTypeHints OSFunction = "typing.get_type_hints"
	OSGetenv       OSFunction = "os.getenv"
	OSGetEnviron   OSFunction = "os.environ"
	// OSPathScan reads a bounded subtree in one call, for os.scandir,
	// os.walk, Path.walk, Path.glob and Path.rglob. Args[0] is the root and
	// the keyword arguments are max_depth, follow_symlinks, pattern,
	// case_sensitive and recurse_symlinks. Reply with a list of
	// (relative_path, is_dir, is_file, is_symlink) tuples including the root
	// as "", or with {"matches": [relative_path, ...]} for a glob you
	// selected yourself. Extra entries are harmless: the sandbox re-selects.
	OSPathScan OSFunction = "Path.scan"
	// OSImport asks for a module by top-level name. Reply with a ModuleValue,
	// or raise ModuleNotFoundError. RunOptions.Modules answers these before
	// the OS handler sees them; submodules are Module-valued attributes.
	OSImport OSFunction = "import"
	// OSImportStubs asks for type stubs for imports about to be
	// type-checked; reply with a dict of module name to stub source.
	OSImportStubs OSFunction = "import_stubs"
)

// OSCall describes an OS-level callback requested by Monty.
type OSCall struct {
	Function OSFunction
	Args     []Value
	Kwargs   Dict
	CallID   uint32
}

// Waiter represents a pending external result that will be resolved later.
type Waiter interface {
	Wait(context.Context) Result
}

// ExternalFunction handles a host external function callback.
type ExternalFunction func(context.Context, Call) (Result, error)

// MethodHandler handles a host dataclass method callback.
type MethodHandler = ExternalFunction

// OSHandler handles a host OS callback.
type OSHandler func(context.Context, OSCall) (Result, error)

// PrintCallback receives aggregated stdout text emitted during each execution step.
type PrintCallback func(stream string, text string)

// WriterPrintCallback writes captured stdout to an io.Writer.
func WriterPrintCallback(w io.Writer) PrintCallback {
	return func(_ string, text string) {
		_, _ = io.WriteString(w, text)
	}
}

type resultKind uint8

const (
	resultKindReturn resultKind = iota
	resultKindException
	resultKindPending
	resultKindNotFound
	resultKindModuleFile
)

// Result is the explicit host callback result union.
//
// The zero value is treated as `Return(None())`, which keeps simple handlers
// ergonomic while preserving an explicit pending/exception path.
type Result struct {
	kind      resultKind
	value     Value
	exception *Exception
	waiter    Waiter
	module    ModuleFile
}

// ModuleFile is a module's .py source found by the host. The sandbox compiles
// and runs it as the module.
type ModuleFile struct {
	// Path is the virtual path the source was read from: the module's
	// __file__. A path ending in /__init__.py makes the module a package.
	Path string
	// Source is the file's text.
	Source string
}

// Return constructs a successful callback result.
func Return(value Value) Result {
	return Result{
		kind:  resultKindReturn,
		value: value,
	}
}

// Raise constructs a callback result that raises an explicit exception.
func Raise(exception Exception) Result {
	return Result{
		kind:      resultKindException,
		exception: &exception,
	}
}

// NotFound answers a lookup the host does not have. For an import it raises
// ModuleNotFoundError, or the ImportError a from-import of a missing submodule
// raises, which a plain Raise cannot reproduce.
func NotFound() Result {
	return Result{kind: resultKindNotFound}
}

// ImportFile answers an OSImport call with the module's .py source. It is only
// valid for an import whose search path was not empty.
func ImportFile(file ModuleFile) Result {
	return Result{kind: resultKindModuleFile, module: file}
}

// Pending constructs a callback result backed by a waiter.
func Pending(waiter Waiter) Result {
	return Result{
		kind:   resultKindPending,
		waiter: waiter,
	}
}

// ResourceLimits controls Monty execution limits.
//
// A zero MaxDuration/MaxMemory/GCInterval leaves that limit unset (unbounded).
// A zero MaxRecursionDepth/MaxSuspensions instead falls back to upstream's
// own default (1000 for each) — Monty always bounds recursion depth and the
// suspension budget, even when the host asks for "no limits".
type ResourceLimits struct {
	MaxDuration       time.Duration
	MaxMemory         int
	GCInterval        int
	MaxRecursionDepth int
	// MaxSuspensions caps how many external/OS calls Monty will suspend on
	// and wait for the host to service in one session — a backstop against
	// sandboxed code looping on host calls while MaxDuration is paused.
	MaxSuspensions int
}

