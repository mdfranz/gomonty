// complexString formats c as Python's repr(complex) does: "2j" for a plain
// imaginary number, "(1+2j)" otherwise, with -0.0 and non-finite parts kept.
func complexString(c complex128) string {
	part := func(f float64) string {
		switch {
		case math.IsNaN(f):
			return "nan"
		case math.IsInf(f, 1):
			return "inf"
		case math.IsInf(f, -1):
			return "-inf"
		}
		return strconv.FormatFloat(f, 'g', -1, 64)
	}
	re, im := real(c), imag(c)
	imText := part(im)
	if re == 0 && !math.Signbit(re) {
		return imText + "j"
	}
	if !strings.HasPrefix(imText, "-") {
		imText = "+" + imText
	}
	return "(" + part(re) + imText + "j)"
}
