// UnmarshalJSON decodes the stable Rust/Go wire schema for values.
func (v *Value) UnmarshalJSON(data []byte) error {
	var envelope struct {
		Kind ValueKind `json:"kind"`
	}
	if err := json.Unmarshal(data, &envelope); err != nil {
		return err
	}

	switch envelope.Kind {
	case ValueKindNone:
		*v = None()
	case ValueKindEllipsis:
		*v = Ellipsis()
	case ValueKindNotImplemented:
		*v = NotImplemented()
	case ValueKindBool:
		var payload struct {
			Value bool `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Bool(payload.Value)
	case ValueKindInt:
		var payload struct {
			Value int64 `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Int(payload.Value)
	case ValueKindBigInt:
		var payload struct {
			Value string `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		bigValue, ok := new(big.Int).SetString(payload.Value, 10)
		if !ok {
			return fmt.Errorf("invalid bigint %q", payload.Value)
		}
		*v = BigInt(bigValue)
	case ValueKindFloat:
		var payload struct {
			Value float64 `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Float(payload.Value)
	case ValueKindComplex:
		var payload struct {
			Real float64 `json:"real"`
			Imag float64 `json:"imag"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Complex(complex(payload.Real, payload.Imag))
	case ValueKindString:
		var payload struct {
			Value string `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = String(payload.Value)
	case ValueKindBytes:
		var payload struct {
			Value []byte `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Bytes(payload.Value)
	case ValueKindList:
		var payload struct {
			Items []Value `json:"items"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = List(payload.Items...)
	case ValueKindTuple:
		var payload struct {
			Items Tuple `json:"items"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = Value{kind: ValueKindTuple, data: payload.Items}
	case ValueKindNamedTuple:
		var payload NamedTuple
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = NamedTupleValue(payload)
	case ValueKindDict:
		var payload struct {
			Items Dict `json:"items"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = DictValue(payload.Items)
	case ValueKindSet:
		var payload struct {
			Items Set `json:"items"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = SetValue(payload.Items)
	case ValueKindFrozenSet:
		var payload struct {
			Items FrozenSet `json:"items"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = FrozenSetValue(payload.Items)
	case ValueKindException:
		var payload struct {
			Type string  `json:"exc_type"`
			Arg  *string `json:"arg"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = ExceptionValue(Exception{Type: payload.Type, Arg: payload.Arg})
	case ValueKindDecimal:
		var payload struct {
			Value string `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = DecimalValue(Decimal(payload.Value))
	case ValueKindPath:
		var payload struct {
			Value string `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = PathValue(Path(payload.Value))
	case ValueKindClassInstance:
		var payload ClassInstance
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = ClassInstanceValue(payload)
	case ValueKindModule:
		var payload Module
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = ModuleValue(payload)
	case ValueKindFileHandle:
		var payload FileHandle
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = FileHandleValue(payload)
	case ValueKindFunction:
		var payload Function
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = FunctionValue(payload)
	case ValueKindRepr:
		var payload struct {
			Value string `json:"value"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = ReprValue(payload.Value)
	case ValueKindCycle:
		var payload struct {
			Placeholder string `json:"placeholder"`
		}
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = CycleValue(payload.Placeholder)
	case ValueKindDate:
		var payload Date
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = DateValue(payload)
	case ValueKindDateTime:
		var payload DateTime
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = DateTimeValue(payload)
	case ValueKindTimeDelta:
		var payload TimeDelta
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = TimeDeltaValue(payload)
	case ValueKindTimeZone:
		var payload TimeZone
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = TimeZoneValue(payload)
	case ValueKindTime:
		var payload Time
		if err := json.Unmarshal(data, &payload); err != nil {
			return err
		}
		*v = TimeValue(payload)
	default:
		return fmt.Errorf("unknown value kind %q", envelope.Kind)
	}
	return nil
}

func (v Value) String() string {
	switch v.Kind() {
	case ValueKindNone:
		return "None"
	case ValueKindEllipsis:
		return "Ellipsis"
	case ValueKindNotImplemented:
		return "NotImplemented"
	case ValueKindBool, ValueKindInt, ValueKindFloat, ValueKindString:
		return fmt.Sprintf("%v", v.data)
	case ValueKindBigInt:
		return v.data.(*big.Int).String()
	case ValueKindComplex:
		return complexString(v.data.(complex128))
	case ValueKindModule:
		return fmt.Sprintf("<module %q>", v.data.(Module).Name)
	case ValueKindBytes:
		return fmt.Sprintf("%q", v.data.([]byte))
	case ValueKindDecimal:
		return string(v.data.(Decimal))
	case ValueKindPath:
		return string(v.data.(Path))
	case ValueKindException:
		return v.data.(Exception).Error()
	case ValueKindFunction:
		return v.data.(Function).Name
	case ValueKindDate:
		d := v.data.(Date)
		return fmt.Sprintf("%04d-%02d-%02d", d.Year, d.Month, d.Day)
	case ValueKindDateTime:
		dt := v.data.(DateTime)
		base := fmt.Sprintf("%04d-%02d-%02d %02d:%02d:%02d", dt.Year, dt.Month, dt.Day, dt.Hour, dt.Minute, dt.Second)
		if dt.Microsecond != 0 {
			base += fmt.Sprintf(".%06d", dt.Microsecond)
		}
		if dt.OffsetSeconds != nil {
			offset := *dt.OffsetSeconds
			sign := "+"
			if offset < 0 {
				sign = "-"
				offset = -offset
			}
			base += fmt.Sprintf("%s%02d:%02d", sign, offset/3600, (offset%3600)/60)
		}
		return base
	case ValueKindTimeDelta:
		td := v.data.(TimeDelta)
		return fmt.Sprintf("timedelta(days=%d, seconds=%d, microseconds=%d)", td.Days, td.Seconds, td.Microseconds)
	case ValueKindTimeZone:
		tz := v.data.(TimeZone)
		if tz.Name != nil {
			return *tz.Name
		}
		offset := tz.OffsetSeconds
		sign := "+"
		if offset < 0 {
			sign = "-"
			offset = -offset
		}
		return fmt.Sprintf("UTC%s%02d:%02d", sign, offset/3600, (offset%3600)/60)
	case ValueKindTime:
		t := v.data.(Time)
		base := fmt.Sprintf("%02d:%02d:%02d", t.Hour, t.Minute, t.Second)
		if t.Microsecond != 0 {
			base += fmt.Sprintf(".%06d", t.Microsecond)
		}
		if t.OffsetSeconds != nil {
			offset := *t.OffsetSeconds
			sign := "+"
			if offset < 0 {
				sign = "-"
				offset = -offset
			}
			base += fmt.Sprintf("%s%02d:%02d", sign, offset/3600, (offset%3600)/60)
		}
		return base
	case ValueKindClassInstance:
		return v.data.(ClassInstance).ClassType.Name
	case ValueKindFileHandle:
		handle := v.data.(FileHandle)
		return fmt.Sprintf("<file name=%q mode=%q>", handle.Path, handle.Mode)
	case ValueKindRepr, ValueKindCycle:
		return v.data.(string)
	case ValueKindList:
		return reprJoin("[", "]", v.data.([]Value))
	case ValueKindTuple:
		items := []Value(v.data.(Tuple))
		if len(items) == 1 {
			return "(" + reprElement(items[0]) + ",)"
		}
		return reprJoin("(", ")", items)
	case ValueKindNamedTuple:
		nt := v.data.(NamedTuple)
		parts := make([]string, len(nt.Values))
		for i, fv := range nt.Values {
			name := ""
			if i < len(nt.FieldNames) {
				name = nt.FieldNames[i]
			}
			parts[i] = fmt.Sprintf("%s=%s", name, reprElement(fv))
		}
		return fmt.Sprintf("%s(%s)", nt.TypeName, strings.Join(parts, ", "))
	case ValueKindDict:
		pairs := v.data.(Dict)
		parts := make([]string, len(pairs))
		for i, p := range pairs {
			parts[i] = fmt.Sprintf("%s: %s", reprElement(p.Key), reprElement(p.Value))
		}
		return "{" + strings.Join(parts, ", ") + "}"
	case ValueKindSet:
		items := []Value(v.data.(Set))
		if len(items) == 0 {
			return "set()"
		}
		return reprJoin("{", "}", items)
	case ValueKindFrozenSet:
		items := []Value(v.data.(FrozenSet))
		if len(items) == 0 {
			return "frozenset()"
		}
		return "frozenset(" + reprJoin("{", "}", items) + ")"
	default:
		typeName := string(v.Kind())
		typeName = strings.ReplaceAll(typeName, "_", " ")
		return typeName
	}
}

// reprElement renders a Value the way Python's repr() would when it appears
// nested inside a container: strings get quoted (str(['a']) == "['a']", not
// "[a]"), everything else defers to String(), which already recurses
// correctly for nested containers.
func reprElement(v Value) string {
	if v.Kind() == ValueKindString {
		return quotePythonString(v.data.(string))
	}
	return v.String()
}

// reprJoin renders a bracketed, comma-separated container repr, e.g.
// reprJoin("[", "]", items) -> "[1, 'a', [2, 3]]".
func reprJoin(open, close string, items []Value) string {
	parts := make([]string, len(items))
	for i, item := range items {
		parts[i] = reprElement(item)
	}
	return open + strings.Join(parts, ", ") + close
}

// quotePythonString approximates CPython's str.__repr__: prefers single
// quotes, switches to double quotes when the string contains a single quote
// but no double quote, and escapes backslashes, the chosen quote character,
// and common control characters.
func quotePythonString(s string) string {
	quote := byte('\'')
	if strings.ContainsRune(s, '\'') && !strings.ContainsRune(s, '"') {
		quote = '"'
	}
	var b strings.Builder
	b.WriteByte(quote)
	for _, r := range s {
		switch {
		case byte(r) == quote && r < 128:
			b.WriteByte('\\')
			b.WriteRune(r)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\r':
			b.WriteString(`\r`)
		case r == '\t':
			b.WriteString(`\t`)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte(quote)
	return b.String()
}

