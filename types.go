type FeedStartOptions struct {
	Inputs map[string]Value
}

// RunOptions configures the high-level runner helper loop.
type RunOptions struct {
	Inputs    map[string]Value
	Functions map[string]ExternalFunction
	OS        OSHandler
	// Modules are host modules the sandbox can import, keyed by top-level
	// name. They are answered before OS, which still sees any other import.
	Modules map[string]Module
	Print   PrintCallback
	Limits  *ResourceLimits
	// Telemetry is nil by default, which fully disables telemetry: no
	// spans are created and no telemetry-related code runs.
	Telemetry        TelemetryHandler
	TelemetryOptions TelemetryOptions
}

// FeedOptions configures the high-level REPL helper loop.
type FeedOptions struct {
	Inputs    map[string]Value
	Functions map[string]ExternalFunction
	OS        OSHandler
	// Modules are host modules the sandbox can import; see RunOptions.Modules.
	Modules map[string]Module
	Print   PrintCallback
	// Telemetry is nil by default, which fully disables telemetry: no
	// spans are created and no telemetry-related code runs.
	Telemetry        TelemetryHandler
	TelemetryOptions TelemetryOptions
}

